const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  'zh-TW': zhTW,
  en,
};

export type Translator = (key: TranslationKey | string, values?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: TranslationKey | string, values: Record<string, string | number> = {}): string {
  const dictionary = dictionaries[locale] as Record<string, string>;
  const fallback = zhTW as Record<string, string>;
  const template = dictionary[key] ?? fallback[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function translator(locale: Locale): Translator {
  return (key, values) => translate(locale, key, values);
}

export function errorMessage(locale: Locale, error: unknown): string {
  const code = typeof error === 'object' && error && 'code' in error ? String(error.code) : 'generic';
  return translate(locale, `error.${code}`);
}
